namespace {

[[noreturn]] void fail(const char *expression, int line) {
    throw std::runtime_error(
        "line " + std::to_string(line) + ": " + expression);
}

#define CHECK(condition) \
    do { if (!(condition)) fail(#condition, __LINE__); } while (false)

MTensor upload(std::vector<int64_t> shape, const std::vector<float> &values) {
    MTensor tensor = gpu_empty(std::move(shape), DType::Float32);
    std::memcpy(tensor.data_ptr(), values.data(), values.size() * sizeof(float));
    return tensor;
}

std::vector<float> download(const MTensor &tensor) {
    const float *data = tensor.data<float>();
    return std::vector<float>(data, data + tensor.numel());
}

bool writeBytes(const fs::path &path, const std::string &bytes) {
    std::ofstream stream(path, std::ios::binary | std::ios::trunc);
    stream.write(bytes.data(), static_cast<std::streamsize>(bytes.size()));
    return static_cast<bool>(stream);
}

bool rejects(const fs::path &path, const std::string &contents) {
    CHECK(writeBytes(path, contents));
    const float translation[3] = {0, 0, 0};
    try {
        (void)loadGaussianPly(path.string(), 1.0f, translation, false);
        return false;
    } catch (const std::runtime_error &) {
        return true;
    }
}

std::string floats(const std::vector<float> &values) {
    return std::string(reinterpret_cast<const char *>(values.data()),
                       values.size() * sizeof(float));
}

// Saves two degree-1 Gaussians and checks the step and every tensor survive.
void checkRoundTrip(const fs::path &path) {
    MTensor means = upload({2, 3}, {1, 2, 3, 4, 5, 6});
    MTensor scales = upload({2, 3}, {-1, -2, -3, -4, -5, -6});
    MTensor quats = upload({2, 4}, {1, 0, 0, 0, 0.5f, 0.5f, 0.5f, 0.5f});
    MTensor featuresDc = upload({2, 3}, {0.1f, 0.2f, 0.3f, 0.4f, 0.5f, 0.6f});
    std::vector<float> rest(2 * 3 * 3);
    for (size_t i = 0; i < rest.size(); i++) rest[i] = static_cast<float>(i) * 0.01f;
    MTensor featuresRest = upload({2, 3, 3}, rest);
    MTensor opacities = upload({2, 1}, {0.25f, -0.75f});

    GaussianParams params{means, scales, quats, featuresDc, featuresRest,
                          opacities, 1.0f, {0, 0, 0}, false};
    saveGaussianPly(path.string(), params, 1234);

    const float translation[3] = {0, 0, 0};
    const LoadedGaussians loaded =
        loadGaussianPly(path.string(), 1.0f, translation, false);
    CHECK(loaded.step == 1234);
    CHECK(download(loaded.means) == download(means));
    CHECK(download(loaded.scales) == download(scales));
    CHECK(download(loaded.quats) == download(quats));
    CHECK(download(loaded.featuresDc) == download(featuresDc));
    CHECK(download(loaded.featuresRest) == rest);
    CHECK(download(loaded.opacities) == download(opacities));
}

void checkMalformedFilesRejected(const fs::path &path) {
    const std::string properties =
        "property float x\nproperty float y\nproperty float z\n"
        "property float f_dc_0\nproperty float f_dc_1\nproperty float f_dc_2\n"
        "property float opacity\n"
        "property float scale_0\nproperty float scale_1\nproperty float scale_2\n"
        "property float rot_0\nproperty float rot_1\nproperty float rot_2\nproperty float rot_3\n";
    const auto header = [&](const std::string &count) {
        return "ply\nformat binary_little_endian 1.0\nelement vertex " + count +
               "\n" + properties + "end_header\n";
    };
    const std::string record = floats(std::vector<float>(14, 0.5f));

    // A file without normals or higher-order SH loads, and the legacy step
    // comment is still recognized.
    std::string legacy = header("1");
    legacy.insert(legacy.find("element"), "comment Generated by msplat at iteration 7\r\n");
    CHECK(writeBytes(path, legacy + record));
    const float translation[3] = {0, 0, 0};
    const LoadedGaussians minimal =
        loadGaussianPly(path.string(), 1.0f, translation, false);
    CHECK(minimal.step == 7);
    CHECK(minimal.means.size(0) == 1);
    CHECK(minimal.featuresRest.size(1) == 0);

    // Counts that overflow or exceed the payload are rejected before allocation.
    CHECK(rejects(path, header("1431655766") + record));
    CHECK(rejects(path, header("99999999999999999999") + record));
    CHECK(rejects(path, header("-1") + record));
    CHECK(rejects(path, header("2") + record));
    // Every truncated record is rejected rather than zero-filled.
    for (size_t length = 0; length < record.size(); length += 7)
        CHECK(rejects(path, header("1") + record.substr(0, length)));
    // Layout problems.
    CHECK(rejects(path, "ply\nformat ascii 1.0\nelement vertex 1\n" + properties +
                        "end_header\n" + record));
    CHECK(rejects(path, "ply\nformat binary_little_endian 1.0\nelement vertex 1\n" +
                        properties));
    std::string doubleX = header("1");
    doubleX.replace(doubleX.find("float x"), 7, "double x");
    CHECK(rejects(path, doubleX + record + std::string(4, '\0')));
    std::string missingRot = header("1");
    missingRot.erase(missingRot.find("property float rot_3\n"), 21);
    CHECK(rejects(path, missingRot + record));
    std::string oddRest = header("1");
    oddRest.insert(oddRest.find("property float opacity"), "property float f_rest_0\n");
    CHECK(rejects(path, oddRest + record + floats({0.0f})));
}

} // namespace

int main(int argc, char **argv) {
    @autoreleasepool {
        const fs::path path = fs::temp_directory_path() /
            ("msplat-gaussian-ply-test-" + std::to_string(static_cast<long long>(getpid())) + ".ply");
        try {
            if (argc != 2)
                throw std::invalid_argument("Expected the metallib path");
            msplat_set_metallib_path_checked(argv[1]);
            checkRoundTrip(path);
            checkMalformedFilesRejected(path);
            fs::remove(path);
            cleanup_msplat_metal();
            return 0;
        } catch (const std::exception &error) {
            fs::remove(path);
            if (std::string(error.what()) ==
                "msplat: no Metal device is available") {
                std::cerr << "SKIP: " << error.what() << '\n';
                return 77;
            }
            std::cerr << error.what() << '\n';
            cleanup_msplat_metal();
            return 1;
        }
    }
}
